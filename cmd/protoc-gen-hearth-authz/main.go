// Command protoc-gen-hearth-authz writes an app's permission checks from the
// Protobuf options of its service.
//
// For each service of the files protoc asks it to generate, it writes the
// service's API interface, the authorizer interface of the RPCs that run on an
// object id, the check of each RPC and the wrapper that runs the check before
// the RPC. The plugin takes hearth's own parameters (app=<id> and
// version=<major.minor.patch>), and it ignores the standard parameters of a Go
// plugin.
//
// docs/specs/permissions.md is the contract of the generated code.
package main

import (
	"fmt"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/pluginpb"

	"github.com/frostyard/hearth/internal/model"
)

// The imports of the generated code.
const (
	authzImport   = protogen.GoImportPath("github.com/frostyard/hearth/authz")
	contextImport = protogen.GoImportPath("context")
)

func main() {
	protogen.Options{ParamFunc: acceptParam}.Run(generate)
}

// acceptParam accepts every plugin parameter. The model reads them itself, so
// that 1 reading checks them for both the plugin and its tests.
func acceptParam(_, _ string) error {
	return nil
}

// Generate generates 1 plugin request. It is the plugin's whole work, without
// the standard input and output, so that a test runs it in memory.
func Generate(req *pluginpb.CodeGeneratorRequest) (*pluginpb.CodeGeneratorResponse, error) {
	gen, err := protogen.Options{ParamFunc: acceptParam}.New(req)
	if err != nil {
		return nil, fmt.Errorf("read the plugin request: %w", err)
	}
	if err := generate(gen); err != nil {
		return nil, err
	}
	return gen.Response(), nil
}

// generate builds the app's model, checks every service, and writes 1 file for
// each generated file that holds a service.
func generate(gen *protogen.Plugin) error {
	// protoc and buf refuse a plugin that does not declare this feature for a
	// file with a proto3 optional field, so both main and Generate declare it.
	gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
	app, err := model.BuildGo(gen)
	if err != nil {
		return err
	}
	operations := make(map[protoreflect.FullName]model.Operation, len(app.Operations))
	for _, op := range app.Operations {
		operations[op.Method.FullName()] = op
	}

	// Check every service before any file is written, so that a refused RPC
	// writes no file.
	for _, file := range gen.Files {
		if !file.Generate {
			continue
		}
		for _, service := range file.Services {
			for _, method := range service.Methods {
				if method.Desc.IsStreamingClient() || method.Desc.IsStreamingServer() {
					return fmt.Errorf("%s: protoc-gen-hearth-authz does not generate the permission check of a streaming RPC",
						method.Desc.FullName())
				}
			}
		}
	}

	for _, file := range gen.Files {
		if !file.Generate || len(file.Services) == 0 {
			continue
		}
		if err := generateFile(gen, file, operations); err != nil {
			return err
		}
	}
	return nil
}

// generateFile writes the permission checks of 1 generated file.
func generateFile(gen *protogen.Plugin, file *protogen.File, operations map[protoreflect.FullName]model.Operation) error {
	out := &output{g: gen.NewGeneratedFile(file.GeneratedFilenamePrefix+"_hearth_authz.go", file.GoImportPath)}
	out.p("// Code generated by protoc-gen-hearth-authz. DO NOT EDIT.")
	out.p("")
	out.p("package %s", file.GoPackageName)
	out.p("")
	for _, service := range file.Services {
		if err := out.service(service, operations); err != nil {
			return err
		}
	}
	return nil
}

// output writes the generated file.
type output struct {
	g *protogen.GeneratedFile
}

// p writes 1 line.
func (o *output) p(format string, args ...any) {
	o.g.P(fmt.Sprintf(format, args...))
}

// ident returns 1 qualified identifier of 1 import path.
func (o *output) ident(path protogen.GoImportPath, name string) string {
	return o.g.QualifiedGoIdent(path.Ident(name))
}

// authzName returns 1 qualified identifier of the authz package.
func (o *output) authzName(name string) string {
	return o.ident(authzImport, name)
}

// contextType returns the context type of the generated code.
func (o *output) contextType() string {
	return o.ident(contextImport, "Context")
}

// requestType returns the pointer type of 1 message.
func (o *output) requestType(message *protogen.Message) string {
	return "*" + o.g.QualifiedGoIdent(message.GoIdent)
}

// txFuncType returns the transaction function type of the generated code.
func (o *output) txFuncType() string {
	return o.authzName("TxFunc") + "[Tx]"
}

// service writes 1 service's API, authorizer, checks and wrapper.
func (o *output) service(service *protogen.Service, operations map[protoreflect.FullName]model.Operation) error {
	name := service.GoName
	full := service.Desc.FullName()

	o.p("// %sAPI is every unary RPC of %s.", name, full)
	o.p("type %sAPI interface {", name)
	for _, method := range service.Methods {
		o.p("%s(%s, %s) (%s, error)", method.GoName, o.contextType(), o.requestType(method.Input), o.requestType(method.Output))
	}
	o.p("}")
	o.p("")

	hookMethods := make([]*protogen.Method, 0, len(service.Methods))
	for _, method := range service.Methods {
		if op, ok := operations[method.Desc.FullName()]; ok && len(op.ObjectIDs) > 0 {
			hookMethods = append(hookMethods, method)
		}
	}
	if len(hookMethods) > 0 {
		o.p("// %sAuthorizer is the permission hook of each RPC of %s", name, full)
		o.p("// that runs on an object id. The hook reads the stored object inside the")
		o.p("// app's transaction, and checks the object's selector value.")
		o.p("type %sAuthorizer[Tx any] interface {", name)
		for _, method := range hookMethods {
			o.p("Authorize%s(ctx %s, tx Tx, grant %s, req %s) error", method.GoName, o.contextType(), o.authzName("Grant"), o.requestType(method.Input))
		}
		o.p("}")
		o.p("")
		o.p("// %sImpl is every RPC of %s, with the permission", name, full)
		o.p("// hook of each RPC that runs on an object id.")
		o.p("type %sImpl[Tx any] interface {", name)
		o.p("%sAPI", name)
		o.p("%sAuthorizer[Tx]", name)
		o.p("}")
		o.p("")
	} else {
		o.p("// %sImpl is every RPC of %s. The service has no", name, full)
		o.p("// RPC on an object id, so it needs no permission hook.")
		o.p("type %sImpl[Tx any] interface {", name)
		o.p("%sAPI", name)
		o.p("}")
		o.p("")
	}

	for _, method := range service.Methods {
		op, ok := operations[method.Desc.FullName()]
		if !ok {
			return fmt.Errorf("%s: the model holds no operation", method.Desc.FullName())
		}
		check, err := o.check(method, op)
		if err != nil {
			return err
		}
		o.p("// Check%s%s checks the permission of %s.", name, method.GoName, method.Desc.FullName())
		o.p("func Check%s%s(grant %s, req %s) error {", name, method.GoName, o.authzName("Grant"), o.requestType(method.Input))
		o.p("return %s", check)
		o.p("}")
		o.p("")
	}

	o.p("// New%sAuthz returns %s with the permission check of", name, full)
	o.p("// every RPC. inTx runs the app's transaction for each RPC that runs on an")
	o.p("// object id: the hook and the RPC read and change 1 object in 1 transaction.")
	o.p("func New%sAuthz[Tx any](impl %sImpl[Tx], inTx %s) %sAPI {", name, name, o.txFuncType(), name)
	if len(hookMethods) > 0 {
		o.p("if inTx == nil {")
		o.p("panic(%q)", "hearth: New"+name+"Authz needs the app's transaction function, for an object-id RPC")
		o.p("}")
	}
	o.p("return &%s[Tx]{impl: impl, inTx: inTx}", unexported(name))
	o.p("}")
	o.p("")

	o.p("// %s is the API of %s with its permission checks.", unexported(name), full)
	o.p("type %s[Tx any] struct {", unexported(name))
	o.p("impl %sImpl[Tx]", name)
	o.p("inTx %s", o.txFuncType())
	o.p("}")
	o.p("")
	for _, method := range service.Methods {
		op, ok := operations[method.Desc.FullName()]
		if !ok {
			return fmt.Errorf("%s: the model holds no operation", method.Desc.FullName())
		}
		o.method(name, method, op)
	}
	return nil
}

// method writes 1 wrapper method.
func (o *output) method(service string, method *protogen.Method, op model.Operation) {
	response := o.requestType(method.Output)
	o.p("// %s implements %sAPI.", method.GoName, service)
	o.p("func (a *%s[Tx]) %s(ctx %s, req %s) (%s, error) {", unexported(service), method.GoName, o.contextType(), o.requestType(method.Input), response)
	o.p("grant, err := %s(ctx)", o.authzName("GrantFrom"))
	o.p("if err != nil {")
	o.p("return nil, err")
	o.p("}")
	o.p("if err := Check%s%s(grant, req); err != nil {", service, method.GoName)
	o.p("return nil, err")
	o.p("}")
	if len(op.ObjectIDs) == 0 {
		o.p("return a.impl.%s(ctx, req)", method.GoName)
		o.p("}")
		o.p("")
		return
	}
	o.p("var response %s", response)
	o.p("err = a.inTx(ctx, func(ctx %s, tx Tx) error {", o.contextType())
	o.p("if err := a.impl.Authorize%s(ctx, tx, grant, req); err != nil {", method.GoName)
	o.p("return err")
	o.p("}")
	o.p("response, err = a.impl.%s(%s(ctx, tx), req)", method.GoName, o.authzName("WithTx"))
	o.p("return err")
	o.p("})")
	o.p("if err != nil {")
	o.p("return nil, err")
	o.p("}")
	o.p("return response, nil")
	o.p("}")
	o.p("")
}

// check returns the check call of 1 RPC: the selector values of its request, the
// capability alone for an RPC on an object id, and the capability alone for the
// other RPCs.
func (o *output) check(method *protogen.Method, op model.Operation) (string, error) {
	switch {
	case len(op.Selectors) > 0:
		args := make([]string, 0, len(op.Selectors)+1)
		args = append(args, fmt.Sprintf("%q", op.Permission))
		for _, selector := range op.Selectors {
			path, err := o.getter(method.Input, selector.Field)
			if err != nil {
				return "", fmt.Errorf("%s: %w", method.Desc.FullName(), err)
			}
			args = append(args, fmt.Sprintf("%s{Selector: %q, Path: %s}", o.authzName("Sel"), selector.Selector, path))
		}
		return fmt.Sprintf("grant.Check(%s)", strings.Join(args, ", ")), nil
	case len(op.ObjectIDs) > 0:
		return fmt.Sprintf("grant.CheckAny(%q)", op.Permission), nil
	default:
		return fmt.Sprintf("grant.Check(%q)", op.Permission), nil
	}
}

// getter returns the Go expression that reads 1 dotted field path of 1 request
// message, such as req.GetNote().GetGroup().
func (o *output) getter(message *protogen.Message, path string) (string, error) {
	expression := "req"
	current := message
	for _, name := range strings.Split(path, ".") {
		var found *protogen.Field
		for _, field := range current.Fields {
			if string(field.Desc.Name()) == name {
				found = field
				break
			}
		}
		if found == nil {
			return "", fmt.Errorf("the field %q of %q is not in the request message", name, path)
		}
		expression += ".Get" + found.GoName + "()"
		if found.Message != nil {
			current = found.Message
		}
	}
	return expression, nil
}

// unexported returns 1 name with a lowercase first letter.
func unexported(name string) string {
	if name == "" {
		return name
	}
	return strings.ToLower(name[:1]) + name[1:]
}
