// Command protoc-gen-hearth-events writes an app's event publishers from the
// Protobuf options of its event messages.
//
// For each file protoc asks it to generate that holds at least 1 message with
// the hearth_event option, it writes 1 file of publishers, and a file with no
// event message gets none. Each event message gets its events.Spec, a function
// that returns the event of 1 change, and a function that writes that event into
// the outbox of the change's transaction.
//
// The plugin takes hearth's own parameters (app=<id> and version=<major.minor
// .patch>), and it ignores the standard parameters of a Go plugin.
package main

import (
	"fmt"
	"strconv"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/pluginpb"

	"github.com/frostyard/hearth/internal/model"
)

// The imports of the generated code.
const (
	eventsImport  = protogen.GoImportPath("github.com/frostyard/hearth/events")
	contextImport = protogen.GoImportPath("context")
)

// commentWidth is how wide 1 line of a generated doc comment is, before its
// "// ".
const commentWidth = 78

func main() {
	protogen.Options{ParamFunc: acceptParam}.Run(generate)
}

// acceptParam accepts every plugin parameter. The model reads them itself, so
// that 1 reading checks them for both the plugin and its tests.
func acceptParam(_, _ string) error {
	return nil
}

// Generate generates 1 plugin request. It is the plugin's whole work, without
// the standard input and output, so that a test runs it in memory.
func Generate(req *pluginpb.CodeGeneratorRequest) (*pluginpb.CodeGeneratorResponse, error) {
	gen, err := protogen.Options{ParamFunc: acceptParam}.New(req)
	if err != nil {
		return nil, fmt.Errorf("read the plugin request: %w", err)
	}
	if err := generate(gen); err != nil {
		return nil, err
	}
	return gen.Response(), nil
}

// generate builds the app's model, and writes 1 file for each generated file
// that holds an event message.
func generate(gen *protogen.Plugin) error {
	// protoc and buf refuse a plugin that does not declare this feature for a
	// file with a proto3 optional field, so both main and Generate declare it.
	gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
	app, err := model.BuildGo(gen)
	if err != nil {
		return err
	}
	events := make(map[protoreflect.FullName]model.Event, len(app.Events))
	for _, event := range app.Events {
		events[event.Message.FullName()] = event
	}
	for _, file := range gen.Files {
		if !file.Generate {
			continue
		}
		messages := eventMessages(file, events)
		if len(messages) == 0 {
			continue
		}
		generateFile(gen, app, file, messages)
	}
	return nil
}

// message is 1 event message of 1 file: its Go name, and the app's event.
type message struct {
	// goName is the Go name of the message, such as NoteCreated, or
	// Lifecycle_Archived for a nested message.
	goName string
	// fullName is the message's full Protobuf name.
	fullName string
	// event is the app's event of that message.
	event model.Event
}

// addMessage adds 1 message and its nested messages, in the file's order.
func addMessage(list *[]message, m *protogen.Message, events map[protoreflect.FullName]model.Event) {
	if event, ok := events[m.Desc.FullName()]; ok {
		*list = append(*list, message{
			goName:   m.GoIdent.GoName,
			fullName: string(m.Desc.FullName()),
			event:    event,
		})
	}
	for _, nested := range m.Messages {
		addMessage(list, nested, events)
	}
}

// eventMessages returns the event messages of 1 file, in the file's message
// order.
func eventMessages(file *protogen.File, events map[protoreflect.FullName]model.Event) []message {
	list := make([]message, 0, len(events))
	for _, m := range file.Messages {
		addMessage(&list, m, events)
	}
	return list
}

// generateFile writes the publishers of 1 generated file.
func generateFile(gen *protogen.Plugin, app *model.App, file *protogen.File, messages []message) {
	out := &output{g: gen.NewGeneratedFile(file.GeneratedFilenamePrefix+"_hearth_events.go", file.GoImportPath)}
	out.p("// Code generated by protoc-gen-hearth-events. DO NOT EDIT.")
	out.p("")
	out.p("package %s", file.GoPackageName)
	out.p("")
	for _, m := range messages {
		out.event(app.ID, m)
	}
}

// output writes the generated file.
type output struct {
	g *protogen.GeneratedFile
}

// p writes 1 line.
func (o *output) p(format string, args ...any) {
	o.g.P(fmt.Sprintf(format, args...))
}

// ident returns 1 qualified identifier of 1 import path.
func (o *output) ident(path protogen.GoImportPath, name string) string {
	return o.g.QualifiedGoIdent(path.Ident(name))
}

// eventsName returns 1 qualified identifier of the events package.
func (o *output) eventsName(name string) string {
	return o.ident(eventsImport, name)
}

// contextType returns the context type of the generated code.
func (o *output) contextType() string {
	return o.ident(contextImport, "Context")
}

// comment writes 1 doc comment, wrapped to commentWidth.
func (o *output) comment(text string) {
	for _, line := range wrap(text) {
		o.p("// %s", line)
	}
}

// event writes 1 event's spec, its constructor and its emit function.
func (o *output) event(app string, m message) {
	spec := m.event
	if spec.Selector == "" {
		o.comment(fmt.Sprintf("Event%s is the event %s, of the message %s, on the topic %s. The event carries no selector, so its topic has no path.",
			m.goName, spec.Type, m.fullName, spec.Topic))
	} else {
		o.comment(fmt.Sprintf("Event%s is the event %s, of the message %s, on the topic %s and the segments of its path.",
			m.goName, spec.Type, m.fullName, spec.Topic))
	}
	o.spec(app, spec, m.goName)
	o.p("")

	if spec.Selector == "" {
		o.comment(fmt.Sprintf("New%s returns the event %s of the object subject. The event carries no selector, so its topic has no path. Its author is the caller of ctx.",
			m.goName, spec.Type))
		o.p("func New%s(ctx %s, subject string) (%s, error) {", m.goName, o.contextType(), o.eventsName("Event"))
		o.p("return %s(ctx, Event%s, subject, %q)", o.eventsName("New"), m.goName, "")
		o.p("}")
		o.p("")
		o.comment(fmt.Sprintf("Emit%s writes the event %s of the object subject to w: the event carries no selector, so its topic has no path, and w is the outbox of the change's transaction.",
			m.goName, spec.Type))
		o.p("func Emit%s(ctx %s, w %s, subject string) error {", m.goName, o.contextType(), o.eventsName("Writer"))
		o.p("event, err := New%s(ctx, subject)", m.goName)
	} else {
		o.comment(fmt.Sprintf("New%s returns the event %s of the object subject, at path of the selector %s. Its author is the caller of ctx.",
			m.goName, spec.Type, spec.Selector))
		o.p("func New%s(ctx %s, subject, path string) (%s, error) {", m.goName, o.contextType(), o.eventsName("Event"))
		o.p("return %s(ctx, Event%s, subject, path)", o.eventsName("New"), m.goName)
		o.p("}")
		o.p("")
		o.comment(fmt.Sprintf("Emit%s writes the event %s of the object subject, at path of the selector %s, to w: the outbox of the change's transaction.",
			m.goName, spec.Type, spec.Selector))
		o.p("func Emit%s(ctx %s, w %s, subject, path string) error {", m.goName, o.contextType(), o.eventsName("Writer"))
		o.p("event, err := New%s(ctx, subject, path)", m.goName)
	}
	o.p("if err != nil {")
	o.p("return err")
	o.p("}")
	o.p("return w.Write(ctx, event)")
	o.p("}")
	o.p("")
}

// spec writes 1 event's spec, with the fields aligned as gofmt aligns them.
func (o *output) spec(app string, spec model.Event, goName string) {
	type field struct {
		key   string
		value string
	}
	fields := []field{
		{"App", app},
		{"Type", spec.Type},
		{"Topic", spec.Topic},
	}
	if spec.Selector != "" {
		fields = append(fields, field{"Selector", spec.Selector})
	}
	fields = append(fields, field{"ReadPermission", spec.ReadPermission})
	width := 0
	for _, f := range fields {
		width = max(width, len(f.key)+1)
	}
	o.p("var Event%s = %s{", goName, o.eventsName("Spec"))
	for _, f := range fields {
		o.p("%-*s%s,", width+1, f.key+":", strconv.Quote(f.value))
	}
	o.p("}")
}

// wrap returns the words of 1 text, wrapped to commentWidth, as the lines of 1
// doc comment.
func wrap(text string) []string {
	var (
		lines []string
		line  strings.Builder
	)
	for _, word := range strings.Fields(text) {
		if line.Len() > 0 && line.Len()+1+len(word) > commentWidth {
			lines = append(lines, line.String())
			line.Reset()
		}
		if line.Len() > 0 {
			line.WriteByte(' ')
		}
		line.WriteString(word)
	}
	if line.Len() > 0 {
		lines = append(lines, line.String())
	}
	return lines
}
